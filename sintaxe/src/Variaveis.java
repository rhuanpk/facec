public class Variaveis {
    public static void main(String[] args) {
        // DECLARAÇÃO, INICIALIZAÇÃO
        int a1;
        a1 = 0;

        // DECLARAÇÃO & INICIALIZAÇÃO
        int a2 = 0;

        // MÚLTIPLA DECLARAÇÃO
        int a3, b3, c3;
        a3 = 0;
        b3 = 1;
        c3 = 2;

        // MÚLTIPLA INICIALIZAÇÃO
        int a4 = 0, b4 = 1, c4 = 2;

        // ATRIBUIÇÃO ENCADEADA
        int a5, b5, c5;
        a5 = b5 = c5 = 42;

        // CONSTANTE
        final double PI = 3.14159;

        // UNDERSCORE
        int  n1 = 1_000_000;
        long n2 = 1_000_000L;
    }
}
